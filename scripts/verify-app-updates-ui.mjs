import { spawn } from 'node:child_process';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';
import electron from 'electron';
const root = fileURLToPath(new URL('..', import.meta.url));
const output = process.env.BORDEAUX_UPDATES_UI_OUTPUT ? path.resolve(process.env.BORDEAUX_UPDATES_UI_OUTPUT) : await fs.mkdtemp(path.join(os.tmpdir(), 'bordeaux-updates-ui-'));
await fs.mkdir(output, { recursive: true });
const html = path.join(output, 'index.html');
await fs.writeFile(html, `<!doctype html><html><head><meta charset="utf-8"></head><body><div id="root"></div><script type="module" src="${path.join(root, 'scripts/app-updates-ui-harness.jsx')}"></script></body></html>`);
await build({ configFile: false, root: output, base: './', publicDir: false, logLevel: 'error', define: { 'process.env.NODE_ENV': JSON.stringify('development') }, build: { outDir: path.join(output, 'dist'), emptyOutDir: true, minify: false, rollupOptions: { input: html } } });
const env = { ...process.env, BORDEAUX_UPDATES_UI_OUTPUT: output, ELECTRON_DISABLE_SECURITY_WARNINGS: 'true' };
delete env.ELECTRON_RUN_AS_NODE;
console.log('Update UI artifacts: ' + output);
const child = spawn(electron, [path.join(root, 'scripts/verify-app-updates-ui-electron.cjs')], { env, stdio: 'inherit' });
const timer = setTimeout(() => child.kill('SIGKILL'), 60000);
child.on('exit', code => { clearTimeout(timer); process.exitCode = code === 0 ? 0 : 1; });
child.on('error', error => { clearTimeout(timer); console.error(error); process.exitCode = 1; });
